/**
 * Emit `dist/server-route-manifest.json` — the S280 server route manifest in
 * a form a NON-TypeScript consumer can read.
 *
 * The JS clients (phlix-mobile-client) and the non-JS clients
 * (phlix-roku-client: BrightScript, no Node at runtime) vendor a COPY of this
 * JSON and gate their own request-issuing code against it. Like
 * `emit-mcp-scopes.mjs` (S249), this script re-exports the SAME constants the
 * TS build produces — it reads the built bundle, never the server — so the
 * JSON cannot drift from `src/routeManifest.generated.ts`.
 *
 * `test/routeManifest.test.ts` asserts the committed JSON matches the TS
 * manifest, so a stale artifact (someone regenerated the TS file and skipped
 * `npm run build`) is a RED rather than a silently wrong file a client then
 * vendors.
 *
 * Byte-stability: `generatedAt` is taken from the TS provenance (the moment
 * the GENERATOR ran), not `new Date()` here, so repeated builds of the same
 * committed source emit the same bytes.
 *
 * @copyright 2026 Joe Huss <detain@interserver.net>
 * @license MIT
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { SERVER_ROUTE_MANIFEST, SERVER_ROUTE_MANIFEST_PROVENANCE } = await import(
  resolve(root, 'dist/phlix-contracts.js')
);

if (!Array.isArray(SERVER_ROUTE_MANIFEST) || SERVER_ROUTE_MANIFEST.length === 0) {
  throw new Error(
    'refusing to emit an empty server-route-manifest.json — the built bundle exports no SERVER_ROUTE_MANIFEST',
  );
}
const provenance = SERVER_ROUTE_MANIFEST_PROVENANCE;
if (!provenance || !/^[0-9a-f]{40}$/.test(provenance.serverSha ?? '')) {
  throw new Error(
    'refusing to emit server-route-manifest.json without a full 40-char provenance serverSha',
  );
}
if (provenance.total !== SERVER_ROUTE_MANIFEST.length) {
  throw new Error(
    `refusing to emit server-route-manifest.json: provenance total (${provenance.total}) does not match the exported manifest length (${SERVER_ROUTE_MANIFEST.length})`,
  );
}

const out = {
  $comment:
    'GENERATED by scripts/emit-server-route-manifest.mjs from src/routeManifest.generated.ts ' +
    '(which scripts/generate-server-route-manifest.mjs derives from phlix-server). Do not edit. ' +
    'Tuple-exact: [method, pathTemplate] pairs the phlix-server registers; a client request that ' +
    'matches only by substring or prefix is a defect. Clients vendor this file verbatim.',
  provenance: {
    serverSha: provenance.serverSha,
    generatedAt: provenance.generatedAt,
    generator: provenance.generator,
    sources: provenance.sources,
    shared: provenance.shared,
    total: provenance.total,
  },
  routes: SERVER_ROUTE_MANIFEST.map(([method, pathTemplate]) => [method, pathTemplate]),
};

writeFileSync(resolve(root, 'dist/server-route-manifest.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(
  `[emit-server-route-manifest] wrote dist/server-route-manifest.json (${out.routes.length} tuples, server ${out.provenance.serverSha})`,
);

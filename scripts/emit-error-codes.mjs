/**
 * Emit `dist/error-codes.json` — the estate error-code vocabulary in a form a
 * NON-JavaScript consumer can read (error-code doctrine, Wave 1).
 *
 * `phlix-hub` and `phlix-server` are PHP and have no Node, no `package.json`
 * and no npm step in their CI, so they cannot import `@phlix/contracts` the way
 * the JS clients do. They can trivially `json_decode()` a file. This script is
 * the bridge: it re-exports the SAME list the TS build produces, so the JSON
 * cannot drift from `src/errors.ts` — it is generated from the built bundle,
 * never hand-maintained.
 *
 * `test/errors.test.ts` asserts the committed JSON matches `ERROR_CODES` byte
 * for byte, so a stale artifact (someone edited `src/errors.ts` and skipped
 * `npm run build`) is a RED rather than a silently wrong file a consumer then
 * pins against.
 *
 * The JSON shape mirrors `dist/mcp-scopes.json`: a `$comment` provenance marker
 * plus one ordered array of plain wire strings. Order is the registry
 * declaration order in `src/errors.ts` and is part of the contract.
 *
 * @copyright 2026 Joe Huss <detain@interserver.net>
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { ERROR_CODES } = await import(resolve(root, 'dist/phlix-contracts.js'));

if (!Array.isArray(ERROR_CODES) || ERROR_CODES.length === 0) {
  throw new Error(
    'refusing to emit an empty error-codes.json — the built bundle exports no ERROR_CODES',
  );
}

const out = {
  $comment:
    'GENERATED by scripts/emit-error-codes.mjs from src/errors.ts. Do not edit. ' +
    'Order is the registry declaration order. Machine error codes are the wire ' +
    'SSOT; clients localize by code, server message text is debug fallback.',
  codes: [...ERROR_CODES],
};

writeFileSync(resolve(root, 'dist/error-codes.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`[emit-error-codes] wrote dist/error-codes.json (${out.codes.length} codes)`);

/**
 * Emit `dist/mcp-scopes.json` — the MCP vocabulary in a form a NON-JavaScript
 * consumer can read (S249).
 *
 * `phlix-hub` is PHP and has no Node, no `package.json` and no npm step in its
 * CI, so it cannot import `@phlix/contracts` the way the JS clients do. It can
 * trivially `json_decode()` a file. This script is the bridge: it re-exports
 * the SAME constants the TS build produces, so the JSON cannot drift from
 * `src/mcp.ts` — it is generated from the built bundle, never hand-maintained.
 *
 * `test/mcp.test.ts` asserts the working-copy JSON matches `MCP_SCOPES` —
 * which reddens a forgotten regen whenever the suite runs before a rebuild —
 * and CI adds the committed-freshness gate: `git diff --exit-code --
 * dist/mcp-scopes.json` right after `npm run build`, so a stale COMMITTED
 * artifact is a RED even though the build healed the working copy. Same
 * pattern as `emit-error-codes.mjs`.
 *
 * @copyright 2026 Joe Huss <detain@interserver.net>
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { MCP_SCOPES, MCP_TOKEN_PREFIX } = await import(
  resolve(root, 'dist/phlix-contracts.js')
);

if (!Array.isArray(MCP_SCOPES) || MCP_SCOPES.length === 0) {
  throw new Error(
    'refusing to emit an empty mcp-scopes.json — the built bundle exports no MCP_SCOPES',
  );
}

const out = {
  $comment:
    'GENERATED by scripts/emit-mcp-scopes.mjs from src/mcp.ts. Do not edit. ' +
    'Order is significant: it is McpScopes::all() order and part of the stored ' +
    'representation of mcp_tokens.scopes.',
  scopes: [...MCP_SCOPES],
  tokenPrefix: MCP_TOKEN_PREFIX,
};

writeFileSync(resolve(root, 'dist/mcp-scopes.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`[emit-mcp-scopes] wrote dist/mcp-scopes.json (${out.scopes.length} scopes)`);
